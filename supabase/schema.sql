-- Jalankan di Supabase SQL Editor.
-- Tabel products kompatibel dengan katalog Yuri Florist yang menjadi basis project ini.
create table if not exists public.florist_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  icon text default '✿',
  description text default '',
  sort_order integer not null default 1,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category text not null,
  subcategory text default '',
  name text not null,
  image text default '',
  price numeric(14,2),
  description text default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Tambahkan kolom yang belum ada jika tabel products lama sudah digunakan.
alter table public.products add column if not exists is_active boolean not null default true;
alter table public.products add column if not exists created_at timestamptz not null default now();
alter table public.products add column if not exists name text;
alter table public.products add column if not exists description text default '';
alter table public.products add column if not exists price numeric(14,2);
alter table public.products add column if not exists image text default '';
alter table public.products add column if not exists subcategory text default '';
alter table public.products add column if not exists category text;

