-- Daftar akun yang benar-benar berhak mengelola toko.
create table if not exists public.florist_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.florist_categories enable row level security;
alter table public.products enable row level security;
alter table public.florist_admins enable row level security;

-- SECURITY DEFINER memungkinkan policy memeriksa allowlist tanpa membuka tabel admin.
create or replace function public.is_florist_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.florist_admins where user_id = auth.uid());
$$;
grant execute on function public.is_florist_admin() to authenticated;

drop policy if exists "Public can read active categories" on public.florist_categories;
create policy "Public can read active categories" on public.florist_categories
  for select using (is_active = true or public.is_florist_admin());
drop policy if exists "Admins manage categories" on public.florist_categories;
create policy "Admins manage categories" on public.florist_categories
  for all to authenticated using (public.is_florist_admin()) with check (public.is_florist_admin());

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products" on public.products
  for select using (is_active = true or public.is_florist_admin());
drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products
  for all to authenticated using (public.is_florist_admin()) with check (public.is_florist_admin());

